/**
 * Returns Passnavi examination/subject link URL.
 * - If university ID is known, links directly to `https://passnavi.obunsha.co.jp/univ/[id]/subject/`
 * - Otherwise, falls back to Passnavi search URL.
 */
export function getPassnaviUrl(universityName: string): string {
    const cleanName = universityName.replace(/\s*\(旧名:[^)]+\)/, '').trim();
    const id = PASSNAVI_UNIV_MAP[cleanName];
    if (id) {
        return `https://passnavi.obunsha.co.jp/univ/${id}/subject/`;
    }
    return `https://passnavi.obunsha.co.jp/search_univ/main-list/?keyword=${encodeURIComponent(cleanName)}`;
}

/**
 * Checks if a university has a verified direct Passnavi ID.
 */
export function hasDirectPassnaviId(universityName: string): boolean {
    const cleanName = universityName.replace(/\s*\(旧名:[^)]+\)/, '').trim();
    return Boolean(PASSNAVI_UNIV_MAP[cleanName]);
}
